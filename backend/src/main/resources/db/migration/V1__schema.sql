-- Resonance Planner, initial schema (docs/04-modello-dati.md, D38).
-- Conventions (D43): snake_case names, enums stored as text, moments in timestamptz (UTC),
-- calendar days in date, whole numbers in integer (D98). Game rules such as the Waveplate
-- limits stay out of the schema (D33).
-- A CHECK that evaluates to NULL counts as passed: every rule tests IS NOT NULL explicitly.

-- =============================================================================
-- Game catalog: written only by the JSON loader at startup (D39)
-- =============================================================================

CREATE TABLE material (
    id       varchar(60)  PRIMARY KEY,
    name     varchar(100) NOT NULL,
    category varchar(30)  NOT NULL,
    exp      integer,
    icon     varchar(200),
    CONSTRAINT material_category_check
        CHECK (category IN ('CREDIT', 'CHARACTER_EXP', 'ENEMY_DROP', 'BOSS_DROP', 'LOCAL_SPECIALTY')),
    -- Only EXP materials (Resonance Potions) carry an EXP value
    CONSTRAINT material_exp_check
        CHECK ((category = 'CHARACTER_EXP' AND exp IS NOT NULL AND exp > 0)
            OR (category <> 'CHARACTER_EXP' AND exp IS NULL))
);

CREATE TABLE farming_source (
    id              varchar(60)  PRIMARY KEY,
    name            varchar(120) NOT NULL,
    type            varchar(30)  NOT NULL,
    waveplate_cost  integer      NOT NULL,
    minutes_per_run integer      NOT NULL,
    CONSTRAINT farming_source_type_check
        CHECK (type IN ('SIMULATION_TRAINING', 'BOSS_CHALLENGE', 'OVERWORLD_ENEMIES', 'OVERWORLD_COLLECTION')),
    CONSTRAINT farming_source_waveplate_cost_check CHECK (waveplate_cost >= 0),
    CONSTRAINT farming_source_minutes_per_run_check CHECK (minutes_per_run > 0)
);

CREATE TABLE farming_drop (
    id                bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farming_source_id varchar(60)   NOT NULL REFERENCES farming_source (id),
    material_id       varchar(60)   NOT NULL REFERENCES material (id),
    avg_quantity      numeric(8, 2) NOT NULL,
    -- true when the number is our own estimate (D25)
    estimated         boolean       NOT NULL DEFAULT false,
    CONSTRAINT farming_drop_avg_quantity_check CHECK (avg_quantity > 0),
    CONSTRAINT farming_drop_source_material_key UNIQUE (farming_source_id, material_id)
);

CREATE TABLE level_exp (
    level       integer PRIMARY KEY,
    exp_to_next integer NOT NULL,
    CONSTRAINT level_exp_level_check CHECK (level >= 1),
    CONSTRAINT level_exp_exp_to_next_check CHECK (exp_to_next > 0)
);

CREATE TABLE game_character (
    id          varchar(60)  PRIMARY KEY,
    name        varchar(100) NOT NULL,
    element     varchar(20)  NOT NULL,
    weapon_type varchar(20)  NOT NULL,
    rarity      integer      NOT NULL,
    role        varchar(60)  NOT NULL,
    icon        varchar(200),
    CONSTRAINT game_character_element_check
        CHECK (element IN ('AERO', 'ELECTRO', 'FUSION', 'GLACIO', 'HAVOC', 'SPECTRO')),
    CONSTRAINT game_character_weapon_type_check
        CHECK (weapon_type IN ('BROADBLADE', 'SWORD', 'PISTOLS', 'GAUNTLETS', 'RECTIFIER')),
    CONSTRAINT game_character_rarity_check CHECK (rarity IN (4, 5))
);

-- One row for each material of each ascension (D34)
CREATE TABLE ascension_cost (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id varchar(60) NOT NULL REFERENCES game_character (id),
    to_rank      integer     NOT NULL,
    material_id  varchar(60) NOT NULL REFERENCES material (id),
    quantity     integer     NOT NULL,
    CONSTRAINT ascension_cost_to_rank_check CHECK (to_rank >= 1),
    CONSTRAINT ascension_cost_quantity_check CHECK (quantity > 0),
    CONSTRAINT ascension_cost_character_rank_material_key UNIQUE (character_id, to_rank, material_id)
);

-- =============================================================================
-- Events: demo events from the JSON loader, others from the admin area (D14)
-- =============================================================================

CREATE TABLE game_event (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- JSON identifier of the demo events; empty for events created by the admin
    code               varchar(60)  UNIQUE,
    name               varchar(120) NOT NULL,
    type               varchar(30)  NOT NULL,
    description        text         NOT NULL,
    schedule_type      varchar(20)  NOT NULL,
    start_date         date,
    end_date           date,
    start_offset_days  integer,
    duration_days      integer,
    repeat_every_days  integer,
    effect_type        varchar(30),
    effect_source_type varchar(30),
    effect_multiplier  numeric(4, 2),
    effect_daily_limit integer,
    CONSTRAINT game_event_type_check CHECK (type IN ('COMBAT_STAGES', 'DOUBLE_DROP', 'POINTS_SHOP')),
    CONSTRAINT game_event_schedule_type_check CHECK (schedule_type IN ('RECURRING', 'FIXED')),
    -- FIXED events use real dates, RECURRING demo events use offsets from today (D29)
    CONSTRAINT game_event_schedule_check CHECK (
        (schedule_type = 'FIXED'
            AND start_date IS NOT NULL AND end_date IS NOT NULL AND end_date >= start_date
            AND start_offset_days IS NULL AND duration_days IS NULL AND repeat_every_days IS NULL)
        OR
        (schedule_type = 'RECURRING'
            AND start_date IS NULL AND end_date IS NULL
            AND start_offset_days IS NOT NULL AND duration_days IS NOT NULL AND repeat_every_days IS NOT NULL
            AND duration_days > 0 AND repeat_every_days >= duration_days)
    ),
    -- Effect type, boosted source type and multiplier are all empty or all filled in (D94)
    CONSTRAINT game_event_effect_check CHECK (
        (effect_type IS NULL AND effect_source_type IS NULL AND effect_multiplier IS NULL
            AND effect_daily_limit IS NULL)
        OR
        (effect_type IS NOT NULL AND effect_source_type IS NOT NULL AND effect_multiplier IS NOT NULL)
    ),
    CONSTRAINT game_event_effect_type_check CHECK (effect_type IN ('DROP_MULTIPLIER')),
    CONSTRAINT game_event_effect_source_type_check CHECK (
        effect_source_type IN ('SIMULATION_TRAINING', 'BOSS_CHALLENGE', 'OVERWORLD_ENEMIES', 'OVERWORLD_COLLECTION')
    ),
    CONSTRAINT game_event_effect_multiplier_check CHECK (effect_multiplier > 1),
    -- How many runs a day get the multiplier; empty = all of them (D94)
    CONSTRAINT game_event_effect_daily_limit_check CHECK (effect_daily_limit > 0)
);

-- Days of the week when the event is active; no rows = active every day (D96)
CREATE TABLE event_active_weekday (
    event_id    bigint      NOT NULL REFERENCES game_event (id) ON DELETE CASCADE,
    day_of_week varchar(10) NOT NULL,
    PRIMARY KEY (event_id, day_of_week),
    CONSTRAINT event_active_weekday_day_of_week_check
        CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);

CREATE TABLE event_activity (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   bigint       NOT NULL REFERENCES game_event (id) ON DELETE CASCADE,
    title      varchar(120) NOT NULL,
    minutes    integer      NOT NULL,
    frequency  varchar(10)  NOT NULL,
    -- Day of the event from which the activity is available; empty = from the first day (D96)
    unlock_day integer,
    position   integer      NOT NULL,
    CONSTRAINT event_activity_minutes_check CHECK (minutes > 0),
    CONSTRAINT event_activity_frequency_check CHECK (frequency IN ('DAILY', 'ONCE')),
    CONSTRAINT event_activity_unlock_day_check CHECK (unlock_day >= 1)
);

CREATE INDEX event_activity_event_id_idx ON event_activity (event_id);

CREATE TABLE event_reward (
    event_id bigint       NOT NULL REFERENCES game_event (id) ON DELETE CASCADE,
    position integer      NOT NULL,
    reward   varchar(120) NOT NULL,
    PRIMARY KEY (event_id, position)
);

-- =============================================================================
-- User data: everything is deleted together with the user (D42)
-- =============================================================================

-- Plural name because "user" is a reserved word in PostgreSQL
CREATE TABLE users (
    id                    bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              varchar(30)  NOT NULL UNIQUE,
    email                 varchar(254) NOT NULL UNIQUE,
    -- BCrypt hash, never the plain password (D45)
    password_hash         varchar(100) NOT NULL,
    role                  varchar(10)  NOT NULL,
    -- Empty until the guided setup is complete (D16)
    play_time_minutes     integer,
    onboarding_completed  boolean      NOT NULL DEFAULT false,
    -- Waveplate snapshot (D28, D36): the current value is calculated when it is read
    waveplate_value       integer,
    waveplate_crystals    integer,
    waveplate_recorded_at timestamptz,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT users_email_lowercase_check CHECK (email = lower(email)),
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN', 'GUEST')),
    CONSTRAINT users_play_time_minutes_check CHECK (play_time_minutes > 0),
    CONSTRAINT users_waveplate_value_check CHECK (waveplate_value >= 0),
    CONSTRAINT users_waveplate_crystals_check CHECK (waveplate_crystals >= 0),
    -- The three snapshot values are saved together
    CONSTRAINT users_waveplate_snapshot_check CHECK (
        (waveplate_value IS NULL AND waveplate_crystals IS NULL AND waveplate_recorded_at IS NULL)
        OR
        (waveplate_value IS NOT NULL AND waveplate_crystals IS NOT NULL AND waveplate_recorded_at IS NOT NULL)
    )
);

-- Characters in the roster; the rules between level and rank are checked by the backend (D34)
CREATE TABLE owned_character (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    character_id  varchar(60) NOT NULL REFERENCES game_character (id),
    current_level integer     NOT NULL,
    current_rank  integer     NOT NULL,
    target_level  integer     NOT NULL,
    target_rank   integer     NOT NULL,
    CONSTRAINT owned_character_level_check CHECK (current_level >= 1 AND target_level >= 1),
    CONSTRAINT owned_character_rank_check CHECK (current_rank >= 0 AND target_rank >= 0),
    CONSTRAINT owned_character_user_character_key UNIQUE (user_id, character_id)
);

CREATE TABLE inventory_item (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    material_id varchar(60) NOT NULL REFERENCES material (id),
    quantity    integer     NOT NULL,
    CONSTRAINT inventory_item_quantity_check CHECK (quantity >= 0),
    CONSTRAINT inventory_item_user_material_key UNIQUE (user_id, material_id)
);

-- =============================================================================
-- Planning and agent
-- =============================================================================

CREATE TABLE plan_proposal (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status     varchar(15) NOT NULL,
    -- Explanation of the plan written by the agent
    summary    text,
    created_at timestamptz NOT NULL DEFAULT now(),
    decided_at timestamptz,
    CONSTRAINT plan_proposal_status_check CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'REPLACED'))
);

CREATE INDEX plan_proposal_user_id_idx ON plan_proposal (user_id);

-- At most one pending proposal per user, even with two requests at the same moment (D37)
CREATE UNIQUE INDEX plan_proposal_one_pending_per_user_idx ON plan_proposal (user_id) WHERE status = 'PENDING';

-- Every calendar activity in a single table (D35)
CREATE TABLE planned_task (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           bigint       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    proposal_id       bigint       REFERENCES plan_proposal (id),
    origin            varchar(10)  NOT NULL,
    kind              varchar(20)  NOT NULL,
    status            varchar(15)  NOT NULL,
    task_date         date         NOT NULL,
    title             varchar(120) NOT NULL,
    notes             text,
    minutes           integer      NOT NULL,
    farming_source_id varchar(60)  REFERENCES farming_source (id),
    runs              integer,
    -- If the event is deleted the task stays, without the link
    event_id          bigint       REFERENCES game_event (id) ON DELETE SET NULL,
    character_id      varchar(60)  REFERENCES game_character (id),
    completed_at      timestamptz,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT planned_task_origin_check CHECK (origin IN ('AGENT', 'MANUAL')),
    CONSTRAINT planned_task_kind_check CHECK (kind IN ('FARMING', 'EVENT', 'CUSTOM')),
    CONSTRAINT planned_task_status_check
        CHECK (status IN ('PROPOSED', 'CONFIRMED', 'DONE', 'REJECTED', 'REPLACED')),
    CONSTRAINT planned_task_minutes_check CHECK (minutes > 0),
    CONSTRAINT planned_task_runs_check CHECK (runs > 0),
    -- FARMING tasks need a source and a number of runs; the other kinds have neither
    CONSTRAINT planned_task_farming_check CHECK (
        (kind = 'FARMING' AND farming_source_id IS NOT NULL AND runs IS NOT NULL)
        OR
        (kind <> 'FARMING' AND farming_source_id IS NULL AND runs IS NULL)
    ),
    CONSTRAINT planned_task_event_check CHECK (kind = 'EVENT' OR event_id IS NULL),
    -- Agent tasks always belong to a proposal; manual tasks are CUSTOM and never do (D24)
    CONSTRAINT planned_task_origin_rules_check CHECK (
        (origin = 'AGENT' AND proposal_id IS NOT NULL)
        OR
        (origin = 'MANUAL' AND kind = 'CUSTOM' AND proposal_id IS NULL)
    )
);

CREATE INDEX planned_task_user_id_task_date_idx ON planned_task (user_id, task_date);
CREATE INDEX planned_task_proposal_id_idx ON planned_task (proposal_id);
-- Speeds up the SET NULL when an event is deleted
CREATE INDEX planned_task_event_id_idx ON planned_task (event_id);

-- Chat with the agent, text only (D40)
CREATE TABLE agent_message (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role        varchar(10) NOT NULL,
    content     text        NOT NULL,
    -- Set when the message produced a proposal
    proposal_id bigint      REFERENCES plan_proposal (id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT agent_message_role_check CHECK (role IN ('USER', 'ASSISTANT'))
);

CREATE INDEX agent_message_user_id_created_at_idx ON agent_message (user_id, created_at);
-- Speeds up the foreign key check when a user and their proposals are deleted
CREATE INDEX agent_message_proposal_id_idx ON agent_message (proposal_id);
